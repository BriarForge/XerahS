"""Render desktop implementation coverage from the contract and traceability."""
from __future__ import annotations

import argparse
from collections import Counter
import importlib.util
import json
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PLATFORMS = {'macos': 'macOS', 'linux': 'Linux', 'windows': 'Windows'}
# CORE-029 explicitly places Android/iOS outside desktop parity measurement.
DESKTOP_EXCLUSIONS = {'CORE-029'}
STATES = {'implemented', 'partial', 'not-started', 'not-applicable'}


def contract(root: Path):
    path = root / 'tools/contract-linter/lint.py'
    spec = importlib.util.spec_from_file_location('platform_progress_contract_lint', path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    findings = module.Findings()
    version, _, capabilities = module.parse_manifest(root / 'product-contract/manifest.yaml', findings)
    if findings.items:
        raise ValueError('\n'.join(findings.items))
    return version, [c for c in capabilities if c.identifier != 'MOBILE-PLATFORM-001']


def count(requirements: list[str], recorded: dict) -> Counter:
    unknown = set(recorded) - set(requirements)
    if unknown:
        raise ValueError(f'Traceability contains unknown requirement IDs: {sorted(unknown)}')
    result = Counter()
    for identifier in requirements:
        row = recorded.get(identifier)
        if row is not None and row.get('status') not in STATES:
            raise ValueError(f'{identifier}: invalid status {row.get("status")!r}')
        if identifier in DESKTOP_EXCLUSIONS:
            continue
        # Other exclusions need an explicit metric review; never silently shrink
        # the denominator because a platform labels a desktop requirement N/A.
        if row and row['status'] == 'not-applicable':
            raise ValueError(f'{identifier}: desktop N/A requires an explicit progress-metric review')
        result[row['status'] if row else 'unassessed'] += 1
    return result


def percent(counts: Counter) -> str:
    total = sum(counts.values())
    return f'{100 * counts["implemented"] / total:.1f}%' if total else 'N/A'


def collect(root: Path, capabilities):
    results = {}
    for platform in PLATFORMS:
        rows = []
        for capability in capabilities:
            base = root / 'platforms' / platform
            trace_dir = base / ('linux-qt/traceability' if platform == 'linux' else 'traceability')
            source = trace_dir / f'{capability.identifier}.json'
            data = json.loads(source.read_text(encoding='utf-8')) if source.exists() else {}
            if data and (data.get('capability') != capability.identifier or data.get('platform') != platform):
                raise ValueError(f'{source}: capability/platform identity mismatch')
            counts = count(capability.requirements, data.get('requirements', {}))
            rows.append((capability, counts, source if source.exists() else None))
        results[platform] = rows
    return results


def link(label: str, path: Path, output: Path) -> str:
    relative = os.path.relpath(path, output.parent).replace('\\', '/')
    return f'[{label}]({relative})'


def render(root: Path) -> dict[Path, str]:
    version, capabilities = contract(root)
    results = collect(root, capabilities)
    totals = {p: sum((c for _, c, _ in rows), Counter()) for p, rows in results.items()}
    overall = sum(totals.values(), Counter())
    files = {}
    outputs = [(None, root / 'platforms/PROGRESS.md')] + [
        (p, root / 'platforms' / p / 'PROGRESS.md') for p in PLATFORMS]
    for platform, output in outputs:
        title = f'{PLATFORMS[platform]} progress' if platform else 'Desktop platform progress'
        lines = [f'# {title}', '', '<!-- Generated by tools/platform-progress/update.py; update traceability, then regenerate. -->', '',
                 f'Product Contract **{version}**. Percentages are **recorded implementation coverage**, not release readiness or an effort estimate.', '',
                 '| Platform | Implementation coverage | Implemented / desktop requirements |', '|---|---:|---:|']
        for p, name in PLATFORMS.items():
            counts = totals[p]
            lines.append(f'| {link(name, root / "platforms" / p / "PROGRESS.md", output)} | **{percent(counts)}** | {counts["implemented"]} / {sum(counts.values())} |')
        lines += [f'| **Overall desktop** | **{percent(overall)}** | **{overall["implemented"]} / {sum(overall.values())} platform-requirement pairs** |', '',
                  'Only requirements explicitly marked `implemented` in a platform traceability map receive credit. Partial, not-started and missing/unassessed rows receive no credit. Overall sums the three platforms\' implemented rows and divides by their combined desktop requirement count.', '',
                  'The mobile capability and mobile-only `CORE-029` are outside this desktop metric, as stated in ' + link('CORE-PLATFORM-001', root / 'product-contract/capabilities/CORE-PLATFORM-001/SPEC.md', output) + '. Android/iOS remain supported targets; no desktop requirement or platform is waived.', '',
                  'Requirement labels are unweighted: a catalogue requirement can cover hundreds of items. These values do not certify current CI, native usability, conformance, security/privacy/accessibility review, cross-platform parity, or release approval. A graph edge or test-file presence does not earn implementation credit.', '',
                  '## Current position', '']
        selected = [platform] if platform else list(PLATFORMS)
        for p in selected:
            c = totals[p]
            lines += [f'- **{PLATFORMS[p]}:** {c["implemented"]} implemented, {c["partial"]} partial, {c["not-started"]} not started, {c["unassessed"]} without a recorded implementation status. ' + link('Native platform evidence', root / 'platforms' / p / 'README.md', output) + '.']
        if platform == 'linux':
            lines += ['', 'Linux figures cover the `linux-qt` reference edition. Candidate editions and supported desktop-environment qualification remain separate. Existing maps retain their recorded audit dates and versions; regenerating this report does not constitute a new implementation audit.', '',
                      'Next work follows the ' + link('implementation plan', root / 'platforms/linux/linux-qt/IMPLEMENTATION.md', output) + ' and ' + link('measured backlog', root / 'platforms/linux/linux-qt/PRODUCTION-BACKLOG.md', output) + '. Check later implementation/evidence commits before acting on an older backlog item.']
        elif platform and not totals[platform]['implemented'] and not totals[platform]['partial']:
            lines += ['', 'The native application is documented as not started. No platform traceability maps currently supply implementation credit. Missing maps mean unassessed requirements, not accepted Unavailable/Not applicable dispositions. Add evidence and traceability as implementation begins.']
        elif platform:
            lines += ['', 'Native implementation coverage follows the platform traceability maps linked below. Review the native README, current test evidence and open qualification gates before declaring readiness.']
        lines += ['', '## Contract coverage', '', '| Capability | Coverage | Implemented | Partial | Not started | Unassessed | Evidence |', '|---|---:|---:|---:|---:|---:|---|']
        for capability in capabilities:
            rows = [next(row for row in results[p] if row[0].identifier == capability.identifier) for p in selected]
            c = sum((row[1] for row in rows), Counter())
            evidence = ', '.join(link(PLATFORMS[p] + ' map', row[2], output) for p, row in zip(selected, rows) if row[2]) or 'No platform trace map'
            spec = root / 'product-contract' / capability.path / 'SPEC.md'
            lines.append(f'| {link(capability.identifier, spec, output)} | {percent(c)} | {c["implemented"]} | {c["partial"]} | {c["not-started"]} | {c["unassessed"]} | {evidence} |')
        lines += ['', '## Next milestones and acceptance gates', '',
                  'Follow ' + link('native implementation readiness', root / 'product-contract/READINESS.md', output) + ': Wave 1 filename generation, post-capture actions, region capture and editor session; then editor expansion and the foundation/catalogues. Existing Linux work follows its more specific implementation plan.', '',
                  '- Keep per-requirement implementation status separate from platform disposition and qualification.',
                  '- Record actual commands, results, source revision and evidence when tests or target qualification run. This reporting change does not claim a fresh native build or test run.',
                  '- Preserve compatibility/migration safeguards and explicit recovery; obtain required human reviews and supported-target conformance/parity evidence before declaring completion.', '',
                  '## Maintenance', '', 'From the repository root:', '', '```powershell', 'python tools/platform-progress/update.py', 'python tools/platform-progress/update.py --check', '```', '',
                  'Update the affected requirement maps when implementation, evidence, blockers or dispositions change, then regenerate **all four** progress files in the same checkpoint. Each desktop platform uses `traceability/<CAPABILITY>.json`; Linux currently uses `linux-qt/traceability/`. The manifest supplies requirement IDs and the denominator. New requirements without recorded status automatically receive no credit. CI rejects stale generated files.', '',
                  'Refresh affected Graphify semantic graphs after changing these Markdown files. EXTRACTED graph relationships can locate explicit evidence; INFERRED relationships must be verified against source and cannot change these counters.', '']
        files[output] = '\n'.join(lines)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        files = render(ROOT)
    except (ValueError, KeyError, json.JSONDecodeError) as error:
        parser.exit(1, f'Progress inputs invalid: {error}\n')
    stale = []
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        parser.exit(1, 'Progress files are stale; run python tools/platform-progress/update.py:\n' + '\n'.join(stale) + '\n')
    print('Desktop progress files are current.' if args.check else 'Updated desktop overview and macOS/Linux/Windows progress files.')


if __name__ == '__main__':
    main()
